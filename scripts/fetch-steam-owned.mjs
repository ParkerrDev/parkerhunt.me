#!/usr/bin/env node
/**
 * Read the real Steam library — playtime, achievements, recently played — and
 * write site/data/steam-owned.json.
 *
 * THIS IS THE FILE THAT MAKES THE HAND-PINNED SEED UNNECESSARY.
 *
 * site/data/steam-seed.json exists because the profile is private and
 * IPlayerService/GetOwnedGames returns an empty list for a private profile. That
 * is true for *anyone else's* key. It is not true for the account's own:
 *
 *   "Private, friends-only, and other privacy settings are not supported unless
 *    you are asking for your own personal details (i.e. the WebAPI key you are
 *    using is linked to the steamID you are requesting)."
 *      — Steamworks documentation, IPlayerService
 *
 * So one free key, generated by the account owner at
 * https://steamcommunity.com/dev/apikey, reads the whole library with real
 * playtime while the profile stays private to everybody else. Nothing has to be
 * made public and nothing has to be typed by hand again.
 *
 * WHERE THE KEY LIVES: the environment, never the repo.
 *
 *   STEAM_API_KEY=xxxx STEAM_ID=7656119... node scripts/fetch-steam-owned.mjs
 *
 * For deploys it belongs in Cloudflare's build environment variables next to
 * RESUME_DEPLOY_KEY, marked as a secret. A Steam key is not nothing — it can
 * read your own account's details — so treat it like the deploy key: never
 * printed, never committed, rotatable from the same page that issued it.
 *
 * WHAT THIS DOES NOT DO: the wishlist. IWishlistService/GetWishlist honours the
 * same owner exception, but wishlist privacy is a separate toggle from profile
 * privacy and this account has not been checked. The seed's wishlist stays
 * authoritative until someone confirms it; see the note at the bottom.
 *
 * Usage:  node scripts/fetch-steam-owned.mjs [out]
 *
 * FAILS SOFT. No key, a bad key, or Steam being down leaves the committed
 * snapshot alone and exits 0 — scripts/fetch-steam.mjs then falls back to the
 * pinned seed exactly as it always has.
 */

import { writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";

const OUT = resolve(process.argv[2] || "site/data/steam-owned.json");
const KEY = process.env.STEAM_API_KEY;
const ID = process.env.STEAM_ID || "76561199054315811";

function bail(reason, quiet = false) {
  if (!quiet) console.warn(`WARNING: Steam library not refreshed (${reason}).`);
  console.warn(
    existsSync(OUT)
      ? "         Keeping the committed steam-owned.json."
      : "         No owned-games snapshot — fetch-steam.mjs will use the pinned seed."
  );
  process.exit(0);
}

if (!KEY) {
  console.log(`
No STEAM_API_KEY in the environment, so the library was not refreshed.

  1. Sign in and open https://steamcommunity.com/dev/apikey (free, instant)
  2. STEAM_API_KEY=xxxx node scripts/fetch-steam-owned.mjs

The profile can stay private. A key belonging to the account reads that
account's own details regardless of its privacy settings — which is the whole
reason site/data/steam-seed.json had to be typed by hand in the first place.
`);
  bail("no key", true);
}

const UA = { "User-Agent": "parkerhunt.me-build/1.0", Accept: "application/json" };

async function api(iface, method, version, params = {}) {
  const u = new URL(`https://api.steampowered.com/${iface}/${method}/${version}/`);
  u.search = new URLSearchParams({ key: KEY, steamid: ID, format: "json", ...params });
  const res = await fetch(u, { headers: UA, signal: AbortSignal.timeout(20000) });
  if (res.status === 401 || res.status === 403) throw new Error(`Steam rejected the key (${res.status})`);
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return res.json();
}

let owned, recent, summary, level;
try {
  /* include_appinfo brings the name and the capsule hashes back with the list,
     which saves one store call per game; include_played_free_games is what
     stops free-to-play hours from silently vanishing. */
  owned = await api("IPlayerService", "GetOwnedGames", "v1", {
    include_appinfo: "1",
    include_played_free_games: "1",
  });
  recent = await api("IPlayerService", "GetRecentlyPlayedGames", "v1", { count: "6" }).catch(() => null);
  summary = await api("ISteamUser", "GetPlayerSummaries", "v2", { steamids: ID }).catch(() => null);
  level = await api("IPlayerService", "GetSteamLevel", "v1").catch(() => null);
} catch (err) {
  bail(err.message);
}

const games = owned?.response?.games;
if (!Array.isArray(games) || games.length === 0) {
  bail(
    "the API returned no games — if the profile is private, check that this key belongs to THIS steamid; " +
      "another account's key cannot see a private library"
  );
}

const rows = games
  .map((g) => ({
    appid: g.appid,
    name: g.name || "",
    minutes: g.playtime_forever || 0,
    hours: Math.round((g.playtime_forever || 0) / 6) / 10,
    minutes_2w: g.playtime_2weeks || 0,
    last_played: g.rtime_last_played ? new Date(g.rtime_last_played * 1000).toISOString().slice(0, 10) : "",
  }))
  .sort((a, b) => b.minutes - a.minutes);

const played = rows.filter((r) => r.minutes > 0);

const p = summary?.response?.players?.[0] || null;
const profile = p
  ? {
      name: p.personaname || "",
      url: p.profileurl || "",
      // 1 = private, 3 = public. Recorded so the site can say honestly why the
      // library is not linkable rather than pretending the profile is open.
      visibility: p.communityvisibilitystate === 3 ? "public" : "private",
      created: p.timecreated ? new Date(p.timecreated * 1000).toISOString().slice(0, 10) : "",
      level: level?.response?.player_level ?? null,
    }
  : null;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  JSON.stringify(
    {
      fetched: new Date().toISOString().slice(0, 10),
      source: "api.steampowered.com IPlayerService — owner key, so a private profile is readable",
      steamid: ID,
      profile,
      owned: rows.length,
      played: played.length,
      hours: Math.round(rows.reduce((a, r) => a + r.minutes, 0) / 60),
      recent: (recent?.response?.games || []).map((g) => ({
        appid: g.appid,
        name: g.name || "",
        minutes_2w: g.playtime_2weeks || 0,
        hours: Math.round((g.playtime_forever || 0) / 6) / 10,
      })),
      games: rows,
    },
    null,
    2
  ) + "\n"
);

console.log(
  `Steam library: ${rows.length} owned, ${played.length} played, ` +
    `${Math.round(rows.reduce((a, r) => a + r.minutes, 0) / 60).toLocaleString("en-US")} hours` +
    (profile ? ` (profile ${profile.visibility}, level ${profile.level ?? "?"})` : "") +
    ` -> ${OUT}`
);
console.log(
  `\nTop five: ${rows.slice(0, 5).map((r) => `${r.name} ${r.hours}h`).join(", ")}`
);
